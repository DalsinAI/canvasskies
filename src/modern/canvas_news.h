#define NEWS_COUNT ((int)(sizeof(news_items) / sizeof(news_items[0])))

static int news_index_for(int chapter, int mission)
{
    int i;
    for (i = 0; i < NEWS_COUNT; ++i)
        if (news_items[i].chapter == chapter &&
            news_items[i].mission == mission)
            return i;
    return -1;
}

